"""Pydantic schemas for every JSON file in a project folder. All models are frozen."""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, TypeAdapter, field_validator

STAGE_NAMES: tuple[str, ...] = (
    "ingest",
    "transcribe",
    "scenes",
    "inspect",
    "describe",
    "script",
    "tts",
    "music",
    "assemble",
    "export",
)


def now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


class Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="ignore")


class StageStatus(str, Enum):
    PENDING = "pending"
    RUNNING = "running"
    DONE = "done"
    FAILED = "failed"
    STALE = "stale"


class StageError(Frozen):
    code: str
    message: str
    retryable: bool = False


class StageState(Frozen):
    status: StageStatus = StageStatus.PENDING
    progress: float | None = None
    started_at: str | None = None
    finished_at: str | None = None
    elapsed_sec: float | None = None
    error: StageError | None = None
    # Identifies the inputs the outputs were built from; used to skip valid re-runs.
    fingerprint: str | None = None


class Settings(Frozen):
    target_ratio: float = 0.2
    language: str = "auto"
    narration_style: str = "kich_tinh"
    # "vieneu" = offline VieNeu-TTS (voice = preset name); "edge" = edge-tts (voice = vi-VN-...Neural).
    # `python -m recap voices` lists valid values.
    tts_engine: Literal["vieneu", "edge"] = "vieneu"
    voice: str = "Hải Đăng"
    tts_rate: str = "+0%"
    tts_pitch: str = "+0Hz"
    vl_model: str = "qwen2.5vl:7b"
    whisper_model: str = "mlx-community/whisper-large-v3-turbo"
    # "translate" = Whisper translates to English (for films not in Vietnamese/English).
    whisper_task: Literal["transcribe", "translate"] = "transcribe"
    scene_detector: Literal["adaptive", "content"] = "adaptive"
    scene_threshold: float | None = None  # None = PySceneDetect default for the detector
    llm_provider: str = "claude_cli"
    claude_model: str = "sonnet"
    # Film sound under narration (0 = muted; it fades back in for `original` lines).
    duck_volume: float = 0.0
    # Background music (absolute path to an audio file, None = no music) and its levels:
    # under narration, and with nobody talking.
    music_file: str | None = None
    music_volume: float = Field(default=0.10, ge=0.0, le=0.5)
    music_bed_volume: float = Field(default=0.25, ge=0.0, le=1.0)
    # "library" = music_file above (or none); "ai" = cues generated by the music stage.
    music_source: Literal["library", "ai"] = "library"
    music_model: Literal["sm-music", "medium"] = "medium"  # Stable Audio 3 DiT
    # Channel branding: bottom banner image and round logo (None = film fills the frame).
    brand_banner: str | None = None
    brand_logo: str | None = None
    subtitle_font: str = "Arial"  # font name (macOS font folders) or path to a .ttf/.ttc/.otf
    min_beat_sec: float = 4
    max_beat_sec: float = 20
    part_size_min: float = 30
    # Index among the source's audio streams; None = the default-disposition track.
    audio_track: int | None = None


class AudioTrack(Frozen):
    index: int  # position among audio streams (0-based), used as 0:a:<index>
    codec: str | None = None
    language: str | None = None
    channels: int | None = None
    sample_rate: int | None = None
    is_default: bool = False


class MediaInfo(Frozen):
    duration: float
    width: int | None = None
    height: int | None = None
    fps: float | None = None
    audio_tracks: list[AudioTrack] = Field(default_factory=list)

    def default_audio_track(self) -> int | None:
        if not self.audio_tracks:
            return None
        return next((t.index for t in self.audio_tracks if t.is_default), self.audio_tracks[0].index)


class Word(Frozen):
    start: float
    end: float
    word: str


class TranscriptSegment(Frozen):
    """One entry of work/transcript.json."""

    id: int
    start: float
    end: float
    text: str
    speaker: str | None = None
    words: list[Word] = Field(default_factory=list)


class Beat(Frozen):
    """One entry of work/scenes.json: a group of consecutive shots (4–20 s by default)."""

    id: str
    start: float
    end: float
    shots: list[tuple[float, float]]
    keyframe: str  # relative to work/
    dialogue: str = ""


class DescribedBeat(Beat):
    """One entry of work/scenes_described.json: a beat plus its visual description."""

    desc: str


TRANSCRIPT_ADAPTER: TypeAdapter[list[TranscriptSegment]] = TypeAdapter(list[TranscriptSegment])
SCENES_ADAPTER: TypeAdapter[list[Beat]] = TypeAdapter(list[Beat])
DESCRIBED_ADAPTER: TypeAdapter[list[DescribedBeat]] = TypeAdapter(list[DescribedBeat])


class Project(Frozen):
    id: str
    title: str
    source_path: str
    created_at: str
    settings: Settings = Field(default_factory=Settings)
    media: MediaInfo | None = None
    stages: dict[str, StageState]

    @field_validator("stages", mode="after")
    @classmethod
    def _all_stages_in_order(cls, stages: dict[str, StageState]) -> dict[str, StageState]:
        """Projects saved before a stage existed get it as pending (e.g. `music`)."""
        return {name: stages.get(name, StageState()) for name in STAGE_NAMES}

    @classmethod
    def new(cls, title: str, source_path: str, settings: Settings | None = None) -> Project:
        return cls(
            id=str(uuid.uuid4()),
            title=title,
            source_path=source_path,
            created_at=now_iso(),
            settings=settings or Settings(),
            stages={name: StageState() for name in STAGE_NAMES},
        )

    def with_stage(self, name: str, state: StageState) -> Project:
        return self.model_copy(update={"stages": {**self.stages, name: state}})
